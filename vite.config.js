import { defineConfig } from 'vite';
import { execSync } from 'child_process';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

function getGitCommit() {
  try {
    const hash = execSync('git rev-parse --short HEAD', {
      stdio: ['ignore', 'pipe', 'ignore']
    })
      .toString()
      .trim();
    const dirty = execSync('git status --porcelain --untracked-files=no', {
      stdio: ['ignore', 'pipe', 'ignore']
    })
      .toString()
      .trim();
    return dirty ? `${hash}-dirty` : hash;
  } catch {
    return 'unknown';
  }
}

const BUILD_COMMIT = getGitCommit();

// Dev-only: expose the commit hash to the local stats probe (and anyone
// poking at the console) without shipping it in the production bundle.
function buildInfoPlugin() {
  return {
    name: 'build-info',
    apply: 'serve',
    transformIndexHtml() {
      return [
        {
          tag: 'script',
          children: `window.__BUILD_COMMIT__ = ${JSON.stringify(BUILD_COMMIT)};`,
          injectTo: 'head-prepend'
        }
      ];
    }
  };
}

function listFiles(dir, base = dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...listFiles(full, base));
    } else {
      files.push(path.relative(base, full).split(path.sep).join('/'));
    }
  }
  return files;
}

// Emits a generated, precache-everything service worker after the build.
// The file list includes hashed assets, so sw.js changes every build and the
// browser picks up the new cache on the next visit.
function offlineServiceWorker() {
  let outDir = 'dist';

  return {
    name: 'offline-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      const root = path.resolve(process.cwd(), outDir);
      if (!fs.existsSync(root)) return;

      const files = listFiles(root)
        .filter((file) => file !== 'sw.js' && !file.endsWith('.map'))
        .sort();

      // Hash file contents, not just names: Vite hashes JS/CSS filenames, but
      // index.html and public files keep stable names, so content hashing is
      // what guarantees a new worker (and a cache bust) on every real change.
      const hash = crypto.createHash('sha256');
      for (const file of files) {
        hash.update(file);
        hash.update(fs.readFileSync(path.join(root, file)));
      }
      const digest = hash.digest('hex').slice(0, 12);
      const cacheName = `veslo-${digest}`;
      const precache = files.map((file) => `./${file}`);

      const source = `/* Generated by vite.config.js - do not edit. */
const CACHE_NAME = ${JSON.stringify(cacheName)};
const CACHE_PREFIX = 'veslo-';
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const INDEX_URL = './index.html';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => Promise.allSettled(PRECACHE.map((url) => cache.add(url))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys
          .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.includes('/api/debug/')) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy)).catch(() => {});
          return response;
        })
        .catch(() => caches.match(request).then((cached) => cached || caches.match(INDEX_URL)))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy)).catch(() => {});
        }
        return response;
      });
    })
  );
});
`;

      fs.writeFileSync(path.join(root, 'sw.js'), source);
    }
  };
}

export default defineConfig({
  // Relative base so the build works from any subpath (e.g. GitHub Pages
  // project sites at /veslo/) as well as from a custom domain root.
  base: './',
  server: {
    port: 5174
  },
  plugins: [
    {
      name: 'backend-debugger-observability',
      configureServer(server) {
        const debugFlagPath = path.resolve(process.cwd(), '.debug_enabled');
        const debugLogPath = path.resolve(process.cwd(), 'debug.log');

        server.middlewares.use((req, res, next) => {
          if (req.url === '/api/debug/status' && req.method === 'GET') {
            const isEnabled = fs.existsSync(debugFlagPath);
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ enabled: isEnabled }));
            return;
          }

          if (req.url === '/api/debug/toggle' && req.method === 'POST') {
            const isEnabled = fs.existsSync(debugFlagPath);
            if (isEnabled) {
              try { fs.unlinkSync(debugFlagPath); } catch (e) {}
            } else {
              fs.writeFileSync(debugFlagPath, 'true\n');
            }
            const newState = !isEnabled;
            console.log(`[BACKEND DEBUGGER] Toggled -> ${newState ? 'ENABLED' : 'DISABLED'}`);
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ enabled: newState }));
            return;
          }

          if (req.url === '/api/debug/log' && req.method === 'POST') {
            let body = '';
            req.on('data', chunk => { body += chunk; });
            req.on('end', () => {
              try {
                const data = JSON.parse(body);
                const logLine = `[${new Date().toISOString()}] [${data.type || 'LOG'}] ${data.message} ${data.data ? JSON.stringify(data.data) : ''}\n`;
                fs.appendFileSync(debugLogPath, logLine);
                // Also print to server console for task output visibility
                console.log(`[GAME TELEMETRY] ${logLine.trim()}`);
              } catch (e) {}
              res.setHeader('Content-Type', 'application/json');
              res.end(JSON.stringify({ ok: true }));
            });
            return;
          }

          next();
        });
      }
    },
    buildInfoPlugin(),
    offlineServiceWorker()
  ]
});
